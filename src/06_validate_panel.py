"""Runbook Step 3 validation checks -> outputs/validation.md"""
import re, numpy as np, pandas as pd, openpyxl
P = pd.read_csv("data/processed/vendor_panel.csv"); S = pd.read_csv("data/processed/vendor_segments.csv")
out = ["# Vendor panel validation (runbook Step 3)", "", "Generated by `src/06_validate_panel.py`.", ""]
# 1. region share sums: each firm-quarter must sum to 100±1 under at least one regional scheme
SCHEMES = {"TCS": [["Americas", "Europe", "India", "Asia Pacific", "MEA"]], "Infosys": [["North America", "Europe", "Rest of world", "India"]],
  "Wipro": [["Americas", "Europe", "India & Middle East business", "APAC and Other Emerging Markets"], ["Americas", "Europe", "Rest of the World"], ["Americas 1", "Americas 2", "Europe", "APMEA"]],
  "TechM": [["Americas", "Europe", "Rest of world"]], "HCLTech": [["Americas", "Europe", "RoW"], ["Americas", "Europe", "ROW"], ["USA", "Europe [svc]", "ROW [svc]", "India"]],
  "LTI (standalone)": [["North America", "Europe", "Rest of world", "India"]], "LTIMindtree": [["North America", "Europe", "Rest of world"], ["North America", "Europe", "Rest of world", "India"]]}
R = S[S.segment_type == "region"]; fails = []
for (f, q), g in R.groupby(["firm", "cal_quarter_end"]):
    lab = dict(zip(g.segment_label, g.share_pct)); sums = [sum(lab[c] for c in sch) for sch in SCHEMES.get(f, []) if all(c in lab for c in sch)]
    if not any(abs(s - 100) <= 1 for s in sums): fails.append((f, q, [round(s, 1) for s in sums]))
out += ["## 1. Regional shares sum to 100 ± 1", "", f"Firm-quarters checked: {R.groupby(['firm','cal_quarter_end']).ngroups}. Failures: {len(fails)}.", ""]
out += [f"- {f} {q}: sums {s}" for f, q, s in fails] + [""]
# 2. summed quarterly revenue vs reported annual (TCS, TechM)
def tcs_fy():
    ws = openpyxl.load_workbook("data/raw/manual/TCS-Data-Sheet-Q2FY27.xlsx", data_only=True, read_only=True)["IFRS-PnL,BS-USD-Historical"]
    d = list(ws.iter_rows(values_only=True)); h = d[0]
    row = next(r for r in d if isinstance(r[0], str) and r[0].strip() == "Total Revenue")
    return {2000 + int(h[j][2:]): v for j, v in enumerate(row) if isinstance(h[j], str) and re.fullmatch(r"FY\d{2}", h[j]) and isinstance(v, (int, float))}
def techm_fy():
    d = list(openpyxl.load_workbook("data/raw/techm/tml-q2-fy-27-datasheet.xlsx", data_only=True, read_only=True)["P&L US$ mn"].iter_rows(values_only=True))
    fy, out_ = None, {}; row = next(r for r in d if r[0] == "Revenue From Operations")
    for j, (a, b) in enumerate(zip(d[0], d[1])):
        if isinstance(a, str) and (m := re.search(r"FY ?\d{4}-(\d{2})", a)): fy = 2000 + int(m.group(1))
        if b == "Total" and fy and isinstance(row[j], (int, float)): out_[fy] = row[j]
    return out_
out += ["## 2. Sum of quarterly revenue vs reported annual (US$ mn, within 1%)", "", "| Firm | FY | Sum of quarters | Reported FY | Diff % |", "|---|---|---|---|---|"]
bad2 = 0
for firm, fyd in [("TCS", tcs_fy()), ("TechM", techm_fy())]:
    p = P[P.firm == firm].copy(); p["fy"] = p.fiscal_label.str[-2:].astype(int) + 2000
    qs = p.groupby("fy").agg(s=("revenue_usd_m", "sum"), n=("revenue_usd_m", "count"))
    for fy, rep in sorted(fyd.items()):
        if fy in qs.index and qs.loc[fy, "n"] == 4:
            diff = 100 * (qs.loc[fy, "s"] / rep - 1); bad2 += abs(diff) > 1
            out.append(f"| {firm} | FY{fy%100:02d} | {qs.loc[fy,'s']:,.1f} | {rep:,.1f} | {diff:+.2f}{' ⚠️' if abs(diff) > 1 else ''} |")
out += ["", f"Years outside ±1%: {bad2}. (Wipro, Infosys, HCLTech, LTI: annual totals not extracted; quarterly figures cross-checked across overlapping documents instead.)", ""]
# 3. Xpheno ballpark
FIRMS6 = ["TCS", "Infosys", "Wipro", "HCLTech", "TechM", "LTIMindtree"]
h = P[P.firm.isin(FIRMS6)].pivot_table(index="cal_quarter_end", columns="firm", values="headcount_total")
for d in ["2025-09-30", "2026-09-30"]:
    out.append(f"- Combined headcount of the six firms at {d}: **{h.loc[d].sum():,.0f}** ({', '.join(f'{k} {v:,.0f}' for k, v in h.loc[d].items())})")
chg = h.loc["2026-09-30"].sum() - h.loc["2025-09-30"].sum()
out = out[:-2] + ["## 3. Ballpark vs. Xpheno (822,144 → 797,722, Oct 2025 → Oct 2026)", ""] + out[-2:] + [
    f"- Change Sep 2025 → Sep 2026: **{chg:+,.0f}** ({100*chg/h.loc['2025-09-30'].sum():+.1f}%). Xpheno: −24,422 (−3.0%).",
    "- **Level does not match:** our six-firm total is roughly double Xpheno's figure. TCS alone reports ~598k and Infosys ~333k. So Xpheno is not summing the firms' total reported headcount. It may count only India-based IT/engineering staff, or use a different firm set or definition. We could not verify Xpheno's method from the press report. The level difference is recorded rather than forced to match; the direction and size of the change are what matter for context.", ""]
# 4. QoQ headcount jumps > 10%
P["hc_qoq"] = P.groupby("firm").headcount_total.pct_change(fill_method=None) * 100
j = P[P.hc_qoq.abs() > 10][["firm", "fiscal_label", "cal_quarter_end", "headcount_total", "hc_qoq"]]
out += ["## 4. Quarter-on-quarter headcount changes beyond ±10%", ""] + ([f"- {r.firm} {r.fiscal_label}: {r.hc_qoq:+.1f}% (headcount {r.headcount_total:,.0f})" for r in j.itertuples()] or ["- None."]) + [""]
open("outputs/validation.md", "w").write("\n".join(out)); print("\n".join(out))
